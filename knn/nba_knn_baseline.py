"""## 2. Build the KNN
Each player's 5 closest players by cosine similarity. We search for 6 and drop the first hit, which is always the player himself.
"""

K, METRIC = 5, "cosine"

def build_neighbours(df, features, metric=METRIC, k=K):
    X = df[features].to_numpy(dtype=np.float64)
    dist, idx = NearestNeighbors(n_neighbors=k + 1, metric=metric).fit(X).kneighbors(X)
    rows = []
    for i, query in enumerate(df.player_id):
        hits = [(dist[i, j], idx[i, j]) for j in range(k + 1) if idx[i, j] != i][:k]
        for rank, (d, j) in enumerate(hits, start=1):
            sim = 1 - d if metric == "cosine" else 1 / (1 + d)      # higher = more similar
            rows.append((query, rank, df.player_id.iloc[j], round(float(sim), 4)))
    return pd.DataFrame(rows, columns=["query_id", "rank", "neighbour_id", "similarity"])

