"""### 3.3 Do neighbours play the same position?
Each row adds to 100%. A strong diagonal means matches stay within a position. The title compares this with picking players at random, the same "same position" baseline the shared evaluation uses.
"""

nb = neighbours.assign(qpos=neighbours.query_id.map(pos_of), npos=neighbours.neighbour_id.map(pos_of))
